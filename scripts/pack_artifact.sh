# 1g. Canonical-reference allowlist. Any present top-level child other than the
#     named canonical pools (and MANIFEST.sha256) is excluded automatically.
#     This is deliberately an allowlist so a newly copied legacy result tree
#     cannot silently enter a future archive.
exclude_noncanonical_reference_children() {
    local exp="$1"; shift
    local allowed=" MANIFEST.sha256 $* "
    local ref="$ROOT/experiments/$exp/results/reference"
    local child name
    [[ -d "$ref" ]] || return 0
    while IFS= read -r -d '' child; do
        name="$(basename "$child")"
        case "$allowed" in
            *" $name "*) ;;
            *) EX+=( "./experiments/$exp/results/reference/$name" ) ;;
        esac
    done < <(find "$ref" -mindepth 1 -maxdepth 1 -print0)
}

# Root-level compatibility links are subject to the same allowlist. Excluding a
# legacy target but retaining its link would create a dangling archive member.
exclude_noncanonical_reference_links() {
    local exp="$1"; shift
    local allowed=" $* "
    local base="$ROOT/experiments/$exp"
    local link name target
    [[ -d "$base" ]] || return 0
    while IFS= read -r -d '' link; do
        target="$(readlink "$link")"
        [[ "$target" == *results/reference/* ]] || continue
        name="$(basename "$link")"
        case "$allowed" in
            *" $name "*) ;;
            *) EX+=( "./experiments/$exp/$name" ) ;;
        esac
    done < <(find "$base" -mindepth 1 -maxdepth 1 -type l -print0)
}

exclude_noncanonical_results_links() {
