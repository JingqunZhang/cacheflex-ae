    python3 - "$ROOT" "$@" <<'PY'
import configparser
import json
import pathlib
import re
import shlex
import sys

root = pathlib.Path(sys.argv[1])
experiments = sys.argv[2:] or (
    "capacity_motivation",
    "vl_length",
    "end2end",
)
known_experiments = {
    "capacity_motivation",
    "vl_length",
    "end2end",
}
problems = []


unknown_experiments = set(experiments) - known_experiments
if unknown_experiments:
    problems.append(
        f"unknown best-result experiment(s): {sorted(unknown_experiments)}"
    )


target_params = {
    "system.cpu[0].dcache.mshrs": "mshrs",
    "system.tol2bus.header_latency": "header_latency",
    "system.cpu[0].isa[0].sve_vl_se": "vl",
    "system.cpu[0].spmLoadPorts": "spm_load_ports",
    "system.cpu[0].spmStorePorts": "spm_store_ports",
}
config_locations = {
    "mshrs": ("system.cpu.dcache", "mshrs"),
    "header_latency": ("system.tol2bus", "header_latency"),
    "vl": ("system.cpu.isa", "sve_vl_se"),
    "spm_load_ports": ("system.cpu", "spmloadports"),
    "spm_store_ports": ("system.cpu", "spmstoreports"),
}
block_config = {
    "vl4": {
        "vl": "4",
        "spm_load_ports": "2",
        "spm_store_ports": "1",
    },
    "vl16": {
        "vl": "16",
        "spm_load_ports": "1",
        "spm_store_ports": "1",
    },
}


def unsigned(value, label):
    if not isinstance(value, str) or re.fullmatch(r"[0-9]+", value) is None:
        problems.append(f"{label}: expected an unsigned integer, got {value!r}")
        return None
    return str(int(value))


def gem5_spm_defaults():
    """Read defaults used only by Fig. 2 cache-only cells from shipped gem5."""
    source = root / "gem5" / "src" / "cpu" / "o3" / "BaseO3CPU.py"
    try:
        text = source.read_text()
    except OSError as error:
        problems.append(f"cannot read gem5 SPM-port defaults: {error}")
        return {}
    defaults = {}
    for source_name, key in (
        ("spmLoadPorts", "spm_load_ports"),
        ("spmStorePorts", "spm_store_ports"),
    ):
        matches = re.findall(
            rf"^\s*{source_name}\s*=\s*Param\.Unsigned\(\s*([0-9]+)\s*,",
            text,
            re.M,
        )
        if len(matches) != 1:
            problems.append(
                f"{source.relative_to(root)}: expected exactly one numeric "
                f"default for {source_name}, found {len(matches)}"
            )
            continue
        defaults[key] = str(int(matches[0]))
    return defaults


spm_defaults = gem5_spm_defaults()


def gem5_extra_params(cell, label):
    try:
        tokens = shlex.split(cell.get("gem5_extra") or "")
    except (TypeError, ValueError) as error:
        problems.append(f"{label}: invalid gem5_extra: {error}")
        return {}
    params = {}
    index = 0
    while index < len(tokens):
        token = tokens[index]
        assignment = None
        if token == "-P":
            index += 1
            if index >= len(tokens):
                problems.append(f"{label}: gem5_extra ends with bare -P")
                break
            assignment = tokens[index]
        elif token.startswith("-P") and len(token) > 2:
            assignment = token[2:]
        if assignment is not None:
            if "=" not in assignment:
                problems.append(
                    f"{label}: malformed gem5 parameter {assignment!r}"
                )
            else:
                raw_key, raw_value = assignment.split("=", 1)
                key = target_params.get(raw_key)
                if key is not None:
                    value = unsigned(
                        raw_value.strip(),
                        f"{label}: gem5_extra {raw_key}",
                    )
                    if key in params:
                        problems.append(
                            f"{label}: duplicate gem5_extra parameter {raw_key}"
                        )
                    elif value is not None:
                        params[key] = value
        index += 1
    return params


def expected_config(experiment, cell):
    label = f"{experiment}/{cell.get('name', '<unnamed>')}"
    params = gem5_extra_params(cell, label)
    expected = {
        "mshrs": "8",
        "header_latency": "0",
    }
    for fixed in ("mshrs", "header_latency"):
        if fixed in params and params[fixed] != expected[fixed]:
            problems.append(
                f"{label}: gem5_extra {fixed}={params[fixed]}, "
                f"required {expected[fixed]}"
            )

    block = cell.get("block")
    if experiment == "end2end":
        if block is None:
            problems.append(f"{label}: missing configuration block")
            return None
        if block not in block_config:
            problems.append(f"{label}: unknown configuration block {block!r}")
            return None
        derived = block_config[block]
        for key, value in derived.items():
            if key in params and params[key] != value:
                problems.append(
                    f"{label}: gem5_extra {key}={params[key]} conflicts "
                    f"with block {block} ({value})"
                )
        expected.update(derived)
        return expected
    if block is not None:
        problems.append(
            f"{label}: unexpected configuration block outside end2end"
        )
        return None

    vl = params.get("vl")
    if vl not in {"4", "8", "16"}:
        problems.append(
            f"{label}: gem5_extra must specify VL as one of 4, 8, or 16"
        )
        return None
    expected["vl"] = vl

    explicit_ports = {
        key: params[key]
        for key in ("spm_load_ports", "spm_store_ports")
        if key in params
    }
    if len(explicit_ports) == 2:
        expected.update(explicit_ports)
    elif explicit_ports:
        problems.append(
            f"{label}: gem5_extra must specify both SPM load/store ports"
        )
        return None
    elif (
        experiment == "capacity_motivation"
        and pathlib.Path(cell.get("binary", "")).name == "v1_fused"
        and not cell.get("name", "").startswith("v3fused_")
    ):
        # These cache-only Figure 2 cells intentionally omit SPM overrides.
        # Their expected values are the simulator defaults, read above from
        # the exact gem5 source that is included in the artifact.
        if set(spm_defaults) != {"spm_load_ports", "spm_store_ports"}:
            problems.append(f"{label}: cannot derive gem5 SPM-port defaults")
            return None
        expected.update(spm_defaults)
    else:
        problems.append(
            f"{label}: gem5_extra does not specify both SPM load/store ports"
        )
        return None
    return expected


def read_config(path, label):
    config = configparser.ConfigParser(interpolation=None, strict=True)
    try:
        with path.open() as stream:
            config.read_file(stream)
    except (OSError, configparser.Error) as error:
        problems.append(f"{label}: unparseable config.ini: {error}")
        return None
    return config


def check_recorded_config(experiment, cell, config):
    label = f"{experiment}/{cell['name']}"
    expected = expected_config(experiment, cell)
    if expected is None:
        return
    for key, wanted in expected.items():
        section, option = config_locations[key]
        got = config.get(section, option, fallback=None)
        if got is not None:
            got = got.strip()
        if got != wanted:
            problems.append(
                f"{label}: {section}.{option}={got!r}, expected {wanted!r}"
            )


def check_cell(experiment, cell, pool, log_path):
    run_dir = pool / cell["name"]
    required = (run_dir / "config.ini", run_dir / "stats.txt", log_path)
    missing = [
        path.name
        for path in required
        if not path.is_file() or path.stat().st_size == 0
    ]
    if missing:
        problems.append(
            f"{experiment}/{cell['name']}: missing/empty {', '.join(missing)}"
        )
        return
    config = read_config(
        run_dir / "config.ini",
        f"{experiment}/{cell['name']}",
    )
    if config is None:
        return
    check_recorded_config(experiment, cell, config)
    try:
        argv = shlex.split(
            config.get("system.cpu.workload", "cmd", fallback="")
        )
    except ValueError as error:
        problems.append(
            f"{experiment}/{cell['name']}: malformed workload command: {error}"
        )
        argv = []
    expected = shlex.split(cell["args"])
    if len(argv) < 1 or argv[1:] != expected:
        problems.append(
            f"{experiment}/{cell['name']}: recorded args {argv[1:]} "
            f"do not match best.json {expected}"
        )
    expected_binary = pathlib.Path(cell["binary"]).name
    actual_binary = pathlib.Path(argv[0]).name if argv else None
    if actual_binary != expected_binary:
        problems.append(
            f"{experiment}/{cell['name']}: recorded binary {actual_binary} "
            f"does not match best.json {expected_binary}"
        )


for experiment in experiments:
    if experiment not in known_experiments:
        continue
    exp = root / "experiments" / experiment
    try:
        best = json.loads((exp / "best.json").read_text())
        cells = best["cells"]
        if not isinstance(cells, list):
            raise TypeError("'cells' is not a list")
    except (OSError, ValueError, KeyError, TypeError) as error:
        problems.append(f"{experiment}: invalid best.json: {error}")
        continue
    names = [cell.get("name") for cell in cells if isinstance(cell, dict)]
    if len(names) != len(cells) or any(not name for name in names):
        problems.append(f"{experiment}: every best.json cell needs a name")
        continue
    identities = [
        (cell.get("block"), cell["name"])
        if experiment == "end2end"
        else cell["name"]
        for cell in cells
    ]
    if len(set(identities)) != len(identities):
        problems.append(f"{experiment}: duplicate best.json cell identity")
        continue
    ref = exp / "results" / "reference"
    for cell in cells:
        name = cell["name"]
        if experiment == "capacity_motivation":
            pool_name = (
                "results_spm_fused_n2048_headh0"
                if name.startswith("v3fused_")
                else "results_fig2_n2048_headh0"
            )
            pool = ref / pool_name
            log_path = pool / f"{name}.log"
        elif experiment == "vl_length":
            pool = ref / "results_headh0"
            log_path = pool / f"{name}.log"
        else:
            pool = ref / "simulation_results" / cell["block"]
            log_path = pool / name / "stdout.log"
        check_cell(experiment, cell, pool, log_path)

        if log_path.is_file() and "[DBG]" in log_path.read_text(errors="ignore"):
            problems.append(
                f"{experiment}/{name}: debug trace remains in canonical log"
            )

for problem in problems:
    print(f"FAIL: canonical result receipt mismatch: {problem}", file=sys.stderr)
raise SystemExit(bool(problems))
PY
}

verify_canonical_interconnect() {
    python3 - "$ROOT" <<'PY'
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
allow = {
    "capacity_motivation": (
        "results_fig2_n2048_headh0",
        "results_spm_fused_n2048_headh0",
    ),
    "vl_length": ("results_headh0",),
    "software_alternatives": ("best",),
    "end2end": ("simulation_results/vl4", "simulation_results/vl16"),
}
expected = {
    "frontend_latency": "1",
    "header_latency": "0",
    "forward_latency": "1",
    "response_latency": "1",
}
problems = []
for experiment, pools in allow.items():
    ref = root / "experiments" / experiment / "results" / "reference"
    for pool in pools:
        configs = sorted((ref / pool).rglob("config.ini"))
        if not configs:
            problems.append(f"{experiment}/{pool}: no config.ini files")
            continue
        for path in configs:
            text = path.read_text(errors="ignore")
            match = re.search(
                r"^\[system\.tol2bus\]\n(.*?)(?=^\[)",
                text,
                re.S | re.M,
            )
            section = match.group(1) if match else ""
            bad = []
            for key, wanted in expected.items():
                found = re.search(rf"^{key}=(.*)$", section, re.M)
                actual = found.group(1).strip() if found else None
                if actual != wanted:
                    bad.append(f"{key}={actual}")
            if bad:
                problems.append(
                    f"{path.relative_to(root)}: {', '.join(bad)}"
                )

for problem in problems:
    print(f"FAIL: non-canonical interconnect config: {problem}", file=sys.stderr)
raise SystemExit(bool(problems))
PY
}

verify_archive_symlinks() {
    # Audit the exact member set selected by TAR_EX, not just reference pools.
    # Symlinks remain symlinks in the archive; require every one to be relative,
    # resolve inside this repository, and point to another selected member.
    local -A members=()
    local -a links=()
    local member path target resolved relative
    local fail=0

    while IFS= read -r member; do
        member="${member%% -> *}"
        member="${member%/}"
        [[ "$member" == ./* || "$member" == "." ]] || continue
        members["$member"]=1
        path="$ROOT/${member#./}"
        [[ -L "$path" ]] && links+=( "$member" )
    done < <(
        cd "$ROOT"
        tar "${TAR_EX[@]}" -cvf /dev/null . 2>/dev/null
    )

    for member in "${links[@]}"; do
        path="$ROOT/${member#./}"
        target="$(readlink -- "$path")"
        if [[ "$target" == /* ]]; then
            echo "FAIL: absolute archive symlink: $member -> $target" >&2
            fail=1
            continue
        fi
        if ! resolved="$(readlink -e -- "$path")"; then
            echo "FAIL: broken archive symlink: $member -> $target" >&2
            fail=1
            continue
        fi
        case "$resolved" in
            "$ROOT")
                relative="."
                ;;
            "$ROOT"/*)
                relative="./${resolved#"$ROOT"/}"
                ;;
            *)
                echo "FAIL: archive symlink escapes repository: $member -> $target" >&2
                fail=1
                continue
                ;;
        esac
        if [[ -z "${members[$relative]+selected}" ]]; then
            echo "FAIL: archive symlink target is excluded: $member -> $target" >&2
            fail=1
        fi
    done
    return "$fail"
}

verify_archive_member_types() {
    # A public source/results archive has no reason to contain devices, FIFOs,
    # sockets, or other special filesystem objects.
    local member path
    local fail=0
    while IFS= read -r member; do
        member="${member%% -> *}"
        member="${member%/}"
        [[ "$member" == ./* || "$member" == "." ]] || continue
        path="$ROOT/${member#./}"
        if [[ -L "$path" || -f "$path" || -d "$path" ]]; then
            continue
        fi
        echo "FAIL: unsupported archive member type: $member" >&2
        fail=1
    done < <(
        cd "$ROOT"
        tar "${TAR_EX[@]}" -cvf /dev/null . 2>/dev/null
    )
    return "$fail"
}

verify_no_packaged_binary_magic() {
    # Extension filters are convenient but not authoritative.  Inspect the
    # exact selected regular-file set so an accidentally copied executable,
    # object, library, or WebAssembly module cannot be sealed into a
    # code-and-results-only archive under an innocuous filename.
    (
        cd "$ROOT"
        tar "${TAR_EX[@]}" -cvf /dev/null . 2>/dev/null
    ) | python3 /dev/fd/3 "$ROOT" 3<<'PY'
import pathlib
import struct
import sys

root = pathlib.Path(sys.argv[1])
hits = []
seen = set()
fixed_magic = {
    b"\x7fELF": "ELF",
    b"!<arch>\n": "ar archive",
    b"!<thin>\n": "thin ar archive",
    b"\x00asm": "WebAssembly",
    b"\xfe\xed\xfa\xce": "Mach-O",
    b"\xce\xfa\xed\xfe": "Mach-O",
    b"\xfe\xed\xfa\xcf": "Mach-O",
    b"\xcf\xfa\xed\xfe": "Mach-O",
    b"\xca\xfe\xba\xbe": "Mach-O universal",
    b"\xbe\xba\xfe\xca": "Mach-O universal",
    b"\xca\xfe\xba\xbf": "Mach-O universal",
    b"\xbf\xba\xfe\xca": "Mach-O universal",
}

for line in sys.stdin:
    member = line.rstrip("\n").split(" -> ", 1)[0]
    if member.startswith("./"):
        member = member[2:]
    if not member:
        continue
    path = root / member
    if path in seen or path.is_symlink() or not path.is_file():
        continue
    seen.add(path)
    try:
        with path.open("rb") as stream:
            head = stream.read(4096)
            kind = next(
                (
                    label
                    for magic, label in fixed_magic.items()
                    if head.startswith(magic)
                ),
                None,
            )
            # A valid PE header can legally sit beyond the DOS stub bytes read
            # above. Seek to e_lfanew instead of assuming it is within 4 KiB.
            if kind is None and head.startswith(b"MZ") and len(head) >= 64:
                offset = struct.unpack_from("<I", head, 0x3C)[0]
                if offset <= path.stat().st_size - 4:
                    stream.seek(offset)
                    if stream.read(4) == b"PE\0\0":
                        kind = "PE executable"
    except OSError:
        continue
    if kind is not None:
        hits.append((member, kind))

for member, kind in hits[:100]:
    print(f"FAIL: packaged binary magic ({kind}): {member}", file=sys.stderr)
if len(hits) > 100:
    print(f"FAIL: ... and {len(hits) - 100} more binary files", file=sys.stderr)
if hits:
    raise SystemExit(1)
print(f"OK: {len(seen)} packaged regular files contain no binary object/executable magic.")
PY
}

preflight() {
    local fail=0 p
    for p in "${REQUIRED_WORKFLOW_FILES[@]}"; do
        [[ -f "$ROOT/$p" ]] || { echo "FAIL: required workflow file missing: $p" >&2; fail=1; }
    done
    # gem5/README.md is a clean-build input (embedded into m5/info.py by
    # gem5/src/SConscript); assert it exists AND survives the archive filters.
    if ! ( cd "$ROOT"; tar "${TAR_EX[@]}" -cvf /dev/null ./gem5/README.md 2>/dev/null ) \
            | grep -q 'gem5/README\.md'; then
        echo "FAIL: gem5/README.md must ship (clean gem5 build input)" >&2; fail=1
    fi
    local exp
    for exp in capacity_motivation vl_length software_alternatives end2end; do
        require_canonical_reference_dirs "$exp" || fail=1
    done
    python3 "$ROOT/scripts/reference_integrity.py" check --root "$ROOT" || fail=1
    verify_software_best_coverage || fail=1
    # End-to-end has an explicit legacy-measured reference profile.  Its exact
    # membership/config checks, available receipts, and narrow mode/exit
    # exceptions live in reference_integrity.py and plot_fig9_real.py.  Keep
    # those validators authoritative instead of duplicating the policy here.
    verify_best_result_receipts capacity_motivation vl_length || fail=1
    verify_canonical_interconnect || fail=1
    python3 "$ROOT/experiments/vl_length/audit_results.py" \
        "$ROOT/experiments/vl_length/results/reference/results_headh0" || fail=1
    python3 "$ROOT/experiments/end2end/scripts/plot_fig9_real.py" \
        --check "$ROOT/experiments/end2end/results/reference" || fail=1

    # Broken-symlink audit is limited to the canonical reference allowlist.
    local d l
    for exp in capacity_motivation vl_length software_alternatives end2end; do
        while IFS= read -r d; do
            [[ -d "$ROOT/experiments/$exp/results/reference/$d" ]] || continue
            while IFS= read -r -d '' l; do
                readlink -e "$l" >/dev/null \
                    || { echo "FAIL: broken canonical reference symlink: ${l#"$ROOT"/}" >&2; fail=1; }
            done < <(find "$ROOT/experiments/$exp/results/reference/$d" -type l -print0)
        done < <(canonical_reference_dirs "$exp")
    done

    verify_archive_symlinks || fail=1
    verify_archive_member_types || fail=1
    verify_no_packaged_binary_magic || fail=1

    # Scan exactly the members selected by this script, so excluded campaign
    # staging and developer-only files cannot create false positives.
    if ! (
        cd "$ROOT"
        tar "${TAR_EX[@]}" -cvf /dev/null . 2>/dev/null
    ) | python3 "$ROOT/scripts/reference_integrity.py" privacy --root "$ROOT"; then
        fail=1
    fi
    return $fail
}

