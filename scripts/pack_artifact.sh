nonempty_dir() { [[ -d "$1" && -n "$(find "$1" -mindepth 1 -print -quit 2>/dev/null)" ]]; }

# Print the allowlisted top-level reference directories for one experiment.
canonical_reference_dirs() {
    case "$1" in
        capacity_motivation)
            printf '%s\n' \
                results_fig2_n2048_headh0 \
                results_spm_fused_n2048_headh0 ;;
        vl_length)
            printf '%s\n' results_headh0 ;;
        software_alternatives)
            printf '%s\n' best ;;
        end2end)
            printf '%s\n' simulation_results/vl4 simulation_results/vl16 ;;
        *)
            echo "ERROR: no canonical reference allowlist for experiment: $1" >&2
            return 2 ;;
    esac
}

require_canonical_reference_dirs() {
    local exp="$1" d fail=0
    while IFS= read -r d; do
        [[ -n "$d" ]] || continue
        if ! nonempty_dir "$ROOT/experiments/$exp/results/reference/$d"; then
            echo "FAIL: canonical reference missing/empty: experiments/$exp/results/reference/$d" >&2
            fail=1
        fi
    done < <(canonical_reference_dirs "$exp")
    return "$fail"
}

# Every Figure 8 cell frozen in best.json must have exactly one complete
# directory in the canonical flat best pool.
verify_software_best_coverage() {
    python3 - "$ROOT/experiments/software_alternatives/best.json" \
        "$ROOT/experiments/software_alternatives/results/reference" <<'PY'
import json
import configparser
import pathlib
import re
import shlex
import sys

best_path = pathlib.Path(sys.argv[1])
ref = pathlib.Path(sys.argv[2])
if not best_path.is_file():
    print(f"FAIL: Fig. 8 best.json missing: {best_path}", file=sys.stderr)
    raise SystemExit(1)

def complete(path):
    required = ("config.ini", "stats.txt", "stdout.txt")
    return path.is_dir() and all(
        (path / filename).is_file() and (path / filename).stat().st_size > 0
        for filename in required
    )

cells = json.loads(best_path.read_text())["cells"]
expected_names = {cell["name"] for cell in cells}
if len(expected_names) != len(cells):
    print("FAIL: duplicate Figure 8 best.json cell name", file=sys.stderr)
    raise SystemExit(1)
pool = ref / "best"
actual_names = {path.name for path in pool.iterdir() if path.is_dir()} if pool.is_dir() else set()
problems = []
if actual_names != expected_names:
    problems.append(
        f"canonical cell set differs from best.json: "
        f"missing={sorted(expected_names - actual_names)}, "
        f"extra={sorted(actual_names - expected_names)}"
    )

bad_log = re.compile(
    r"\b(?:fatal|panic|segmentation fault|core dumped)\b|"
    r"\bassert(?:ion)?\b[^\n]{0,256}\bfailed\b|"
    r"simulated exit code not 0|validation failed|SELF_CHECK (?:FAIL|SKIP)|"
    r"\[DBG\]",
    re.I,
)
for cell in cells:
    name = cell["name"]
    path = pool / name
    if not complete(path):
        problems.append(f"{name}: missing/empty config.ini, stats.txt, or stdout.txt")
        continue
    log = (path / "stdout.txt").read_text(errors="ignore")
    if "Exiting @ tick" not in log:
        problems.append(f"{name}: no clean gem5 exit")
    if bad_log.search(log):
        problems.append(f"{name}: crash/assert marker")
    if not re.search(r"[0-9.]+\s+GFLOPS", log):
        problems.append(f"{name}: no GFLOPS result")

    cfg = configparser.ConfigParser(strict=False)
    if not cfg.read(path / "config.ini"):
        problems.append(f"{name}: unparseable config.ini")
        continue
    checks = {
        ("system.cpu.dcache", "mshrs"): "8",
        ("system.cpu.isa", "sve_vl_se"): "16",
        ("system.tol2bus", "header_latency"): "0",
    }
    checks.update({
        ("system.cpu", "spmloadports"): "1",
        ("system.cpu", "spmstoreports"): "1",
    })
    for (section, key), wanted in checks.items():
        got = cfg.get(section, key, fallback=None)
        if got != wanted:
            problems.append(f"{name}: {section}.{key}={got}, expected {wanted}")

    argv = shlex.split(cfg.get("system.cpu.workload", "cmd", fallback=""))
    wanted_args = shlex.split(cell["args"])
    if not argv or pathlib.Path(argv[0]).name != pathlib.Path(cell["binary"]).name:
        problems.append(f"{name}: workload binary does not match best.json")
    # best.json records M N K KC MC.  Figure 8 runners invoke the
    # microkernel as M K N n_iter KC MC.
    expected_argv = [
        wanted_args[0],
        wanted_args[2],
        wanted_args[1],
        "1",
        wanted_args[3],
        wanted_args[4],
    ]
    if argv[1:] != expected_argv:
        problems.append(
            f"{name}: recorded args {argv[1:]} do not match "
            f"best.json {wanted_args}"
        )

    receipts = {
        "RUN_ENV.txt": cell.get("env") or "none",
        "RUNNER_USED.txt": cell["runner"],
        "BINARY_USED.txt": cell["binary"],
    }
    for filename, wanted in receipts.items():
        receipt = path / filename
        got = receipt.read_text().strip() if receipt.is_file() else None
        if got != wanted:
            problems.append(f"{name}: {filename}={got!r}, expected {wanted!r}")
    hashes = path / "BINARIES.sha256"
    if not hashes.is_file():
        problems.append(f"{name}: missing BINARIES.sha256")
    else:
        lines = hashes.read_text().splitlines()
        if len(lines) != 2 or any(
            re.fullmatch(r"[0-9a-f]{64}  [^/\s][^\s]*", line) is None
            for line in lines
        ):
            problems.append(f"{name}: malformed/non-relative BINARIES.sha256")

for problem in problems:
    print(f"FAIL: Figure 8 canonical receipt: {problem}", file=sys.stderr)
raise SystemExit(bool(problems))
PY
}

