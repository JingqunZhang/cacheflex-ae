#!/usr/bin/env bash
# =============================================================================
# pack_artifact.sh — build the PUBLIC artifact-evaluation tarball for CacheFlex
#
#   Output: /tmp/cacheflex_artifact_<YYYYMMDD>.tar.gz   (override with --out)
#           — always written OUTSIDE the repo so it is never packed into itself.
#
# INTERNAL TOOL — this script is itself excluded from the package it builds.
# It packs ONLY this repository (the tree it lives in), never a sibling dev tree.
#
# MODES (no default action — prevents an accidental full pack while gem5
# campaigns are still writing into results dirs):
#   --list             stream the would-be-archived member list to stdout
#                      (pipe through `head`/`grep`; tar is killed by SIGPIPE)
#   --print-excludes   print the fully-expanded exclusion list and exit
#   --estimate         du-based uncompressed size estimate of the include set
#                      (metadata walk only; safe while runs are in flight)
#   --check            run the complete packaging pre-flight without creating
#                      an archive
#   --build            create the tarball. HARD-FAILS the pre-flight if any
#                      canonical reference input is missing, incomplete, or has
#                      a broken symlink. RUN ONLY AFTER THE SIMULATION CAMPAIGN
#                      HAS FINISHED.
#
# WHAT IS KEPT:
#   - all source, kernels, paper experiment build/run scripts, the four
#     data-driven plotters, exactly two project-owned usage documents
#     (README.md + SETUP.md), plus gem5's upstream license files
#   - only the canonical reference subsets consumed by the paper plotters:
#       Fig 2: results_fig2_n2048_headh0 + results_spm_fused_n2048_headh0 (paper shape 256x2048x2048)
#       Fig 7: results_headh0
#       Fig 8: flat best/ pool containing the 12 selected ladder rows
#       Fig 9: simulation_results/{vl4,vl16}
#     Per-cell heavyweight files are stripped (fs/, citations.bib, config.json);
#     stats.txt, config.ini, stdout.log, stdout.txt and *.log are kept.
#     NEVER add -h/--dereference to the tar invocation.
#
# WHAT IS EXCLUDED:
#   - results/generated/** and results/campaign_*/** everywhere (regenerable
#     best/sweep output and author-side in-flight campaign staging)
#   - gem5/build, gem5/util/m5/build, tools/ (regenerated by scons /
#     scripts/setup_tools.sh — internet requirement documented in SETUP.md)
#   - kernel binaries (bin/, bin_gem5/, bin_qemu/, *.o, *_enc.s), __pycache__/,
#     *.pyc, m5out*, and internal/dev-only bookkeeping (see §1a)
#
# NOTE on tar pattern semantics (GNU tar default matching: wildcards ON,
# wildcards-match-slash ON, not anchored): member names start with "./", so a
# leading-"./" pattern is anchored to the repo root; a bare component like
# "__pycache__" matches at any depth; a pattern like "*/results/generated"
# matches that path at any depth (its "*" crosses "/").
# =============================================================================
set -euo pipefail

# Bind packaging and its pre-flight checks to this artifact tree.
unset CACHEFLEX_ROOT BEST_JSON GENERATED_DIR RESULTS_DIR OUTPUT_DIR GEM5 GEM5_SE

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"                    # this repo (DST) — the ONLY tree packed
OUT="/tmp/cacheflex_artifact_$(date +%Y%m%d).tar.gz"    # OUTSIDE the repo

MODE=""
OUT_SET=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --list|--print-excludes|--estimate|--check|--build)
            if [[ -n "$MODE" ]]; then
                echo "ERROR: choose exactly one mode; got --$MODE and $1" >&2
                exit 2
            fi
            MODE="${1#--}"
            shift
            ;;
        --out)
            if (( OUT_SET )); then
                echo "ERROR: --out may be specified only once" >&2
                exit 2
            fi
            if [[ $# -lt 2 || "$2" == --* ]]; then
                echo "ERROR: --out requires a file path" >&2
                exit 2
            fi
            OUT="$2"
            OUT_SET=1
            shift 2
            ;;
        *) echo "usage: $0 --list | --print-excludes | --estimate | --check | --build [--out FILE]" >&2
           exit 2 ;;
    esac
done
if [[ -z "$MODE" ]]; then
    echo "usage: $0 --list | --print-excludes | --estimate | --check | --build [--out FILE]" >&2
    echo "(no default mode: gem5 campaigns may still be writing; see header)" >&2
    exit 2
fi
if (( OUT_SET )) && [[ "$MODE" != build ]]; then
    echo "ERROR: --out is valid only with --build" >&2
    exit 2
fi

# The archive must live OUTSIDE the repo it packs. Resolve --out to an
# absolute physical path first so relative paths (e.g. --out subdir/x.tar.gz
# or ../..-tricks) cannot bypass the check.
OUT="$(cd "$(dirname "$OUT")" 2>/dev/null && pwd -P)/$(basename "$OUT")" || {
    echo "ERROR: --out parent directory does not exist: $OUT" >&2; exit 2; }
case "$OUT" in
    "$ROOT"/*|"$ROOT") echo "ERROR: --out must be OUTSIDE the repo ($ROOT); got: $OUT" >&2; exit 2 ;;
esac
if [[ "$MODE" == build ]]; then
    # Do not follow a caller-supplied output symlink back into the repository,
    # and do not silently overwrite an earlier artifact from the same day.
    [[ ! -L "$OUT" ]] || {
        echo "ERROR: refusing symlink archive output: $OUT" >&2
        exit 2
    }
    [[ ! -e "$OUT" ]] || {
        echo "ERROR: archive output already exists; choose a new --out path: $OUT" >&2
        exit 2
    }
fi

