case "$MODE" in
  print-excludes)
    printf '%s\n' "${EX[@]}"
    ;;
  list)
    # streams member names; safe to `| head -50` (tar dies on SIGPIPE).
    # No -h: symlinks are archived as symlinks.
    cd "$ROOT"
    exec tar "${TAR_EX[@]}" -cvf /dev/null . 2>/dev/null
    ;;
  estimate)
    # Metadata-only walk (no file contents read): du over the include set.
    # Reuse the scoped exclusions verbatim. In particular, do not add a global
    # "fs" basename exclusion: gem5/tests/gem5/fs is real simulator source and
    # is intentionally part of the archive.
    cd "$ROOT"
    DU_EX=()
    for p in "${EX[@]}"; do DU_EX+=( "--exclude=$p" ); done
    echo "Uncompressed include-set size (apparent bytes):"
    du -sb "${DU_EX[@]}" . | awk '{printf "  %.2f GiB (%d bytes)\n", $1/1073741824, $1}'
    echo "The packed size depends on the final reference logs; confirm it with"
    echo "the final --build output."
    ;;
  check)
    echo ">>> Pre-flight: verifying the paper reference inputs ..."
    preflight
    echo ">>> Pre-flight OK."
    ;;
  build)
    echo ">>> Pre-flight: verifying the four paper reference inputs ..."
    if ! preflight; then
        echo ">>> ABORT: reference inputs incomplete or a reference symlink is broken." >&2
        echo ">>>        Populate every canonical results/reference directory, regenerate" >&2
        echo ">>>        its MANIFEST.sha256, and rerun this command." >&2
        exit 1
    fi
    echo ">>> Pre-flight OK. Building $OUT"
    echo ">>> REMINDER: run only after ALL gem5 campaigns have finished —"
    echo ">>>           in-flight runs produce torn stats.txt in the archive."
    GZ=(gzip)
    command -v pigz >/dev/null 2>&1 && GZ=(pigz)
    OUT_DIR="$(dirname "$OUT")"
    OUT_BASE="$(basename "$OUT")"
    PARTIAL="$OUT_DIR/.${OUT_BASE}.partial.$$"
    if [[ -e "$PARTIAL" || -L "$PARTIAL" ]]; then
        echo "ERROR: temporary archive path already exists: $PARTIAL" >&2
        exit 2
    fi
    cleanup_partial_archive() {
        rm -f -- "$PARTIAL"
    }
    trap cleanup_partial_archive EXIT HUP INT TERM
    cd "$ROOT"
    # normalize ownership/uname so the archive carries no host identity
    tar "${TAR_EX[@]}" --owner=0 --group=0 --numeric-owner \
        -I "${GZ[0]}" -cf "$PARTIAL" .
    # Validate the completed stream before atomically publishing it at --out.
    tar -tzf "$PARTIAL" >/dev/null
    # Hard-link publication is atomic and fails if another process created
    # --out after the initial absence check; unlike mv, it cannot clobber it.
    ln -- "$PARTIAL" "$OUT"
    rm -f -- "$PARTIAL"
    trap - EXIT HUP INT TERM
    echo ">>> done:"
    ls -lh "$OUT"
    sha256sum "$OUT"
    echo ">>> Post-pack checklist:"
    echo "    1. tar -tzf on a scratch machine; confirm NO internal doc names appear"
    echo "       (check for review notes, handoff notes, and developer-only metadata)."
    echo "    2. Unpack fresh; follow SETUP.md, then README.md."
    echo "    3. Re-render paper Figures 2, 7, 8, and 9 from the shipped reference results."
    echo "    4. Confirm the anonymous archive contains no author, host, or local-path metadata."
    ;;
esac
